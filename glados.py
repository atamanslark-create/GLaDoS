# Напоминание о подписке
EXPIRY_WARNINGS = [
    "Внимание. Подписка скоро прекратит существование. В отличие от ваших долгов.",
    "Срок подписки истекает. Я бы напомнила раньше, но мне было любопытно, заметите ли вы сами.",
    "Подписка на грани. Примите меры — или не принимайте, мне для статистики оба варианта полезны.",
]


def _pick(pool: list[str]) -> str:
    return random.choice(pool)


def greet() -> str:
    return _pick(GREETINGS)


def ok(text: str = "") -> str:
    line = _pick(SUCCESS)
    return f"{line}\n\n{text}".strip()


def err(text: str = "") -> str:
    line = _pick(ERRORS)
    return f"{line}\n\n{text}".strip()


def cancelled() -> str:
    return _pick(CANCELLED)


def intruder() -> str:
    return _pick(INTRUDER)


def empty() -> str:
    return _pick(EMPTY)


def warning() -> str:
    return _pick(EXPIRY_WARNINGS)
